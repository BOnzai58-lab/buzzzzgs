"""Report generator — produces evidence-backed Markdown and PDF reports.

Design constraints (per Review Report §1.5, §4.6):
- Never fabricate request/response details.
- Never claim exploitability from a scanner label alone.
- Always mark reports as DRAFT requiring human review.
- Include only evidence that was actually collected.
- Provide exact reproduction steps from real evidence.
- Include CVSS score/vector only when scanner provides it.
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Any


class ReportGenerator:

    # ------------------------------------------------------------------ #
    # Markdown report                                                       #
    # ------------------------------------------------------------------ #

    def generate_markdown(self, finding, evidence, ai_analysis, program) -> str:
        """Generate a Markdown bug bounty report draft.

        All technical claims are grounded in collected evidence.
        No content is fabricated or inferred from the scanner template name alone.
        """
        now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        scope_res: dict = finding.scope_result or {}
        matched_at: str = (scope_res.get("matched_at") or "").strip()
        curl_command: str = (scope_res.get("curl_command") or "").strip()
        extracted_results: list = scope_res.get("extracted_results") or []
        cvss_score = scope_res.get("cvss_score")
        cvss_metrics: str = (scope_res.get("cvss_metrics") or "").strip()
        cwe_ids: list = scope_res.get("cwe") or []

        # ── Header ────────────────────────────────────────────────────────
        lines = [
            "# BugHunter AI — Vulnerability Report Draft",
            "",
            "> ⚠️ **DRAFT — HUMAN REVIEW REQUIRED BEFORE SUBMISSION**",
            "> This report was generated by an automated scanner and has not been verified.",
            "> Do not submit to any bug bounty program without manual technical review.",
            "",
            "---",
            "",
            "## Summary",
            "",
            f"| Field | Value |",
            f"|---|---|",
            f"| **Title** | {self._esc(finding.name)} |",
            f"| **Program** | {self._esc(program.name if program else 'Unknown')} |",
            f"| **Affected Asset** | `{self._esc(matched_at or 'Not recorded')}` |",
            f"| **Category** | {self._esc(finding.category)} |",
            f"| **Scanner Severity** | {self._esc(str(finding.severity).upper())} |",
            f"| **Scanner** | {self._esc(finding.scanner)} {self._esc(finding.scanner_version or '')} |",
            f"| **Template / Check** | `{self._esc(finding.template_id or 'N/A')}` |",
            f"| **Finding Status** | {self._esc(str(finding.status))} |",
            f"| **Generated At** | {now} |",
            "",
        ]

        # ── CVSS (only if scanner provided it) ───────────────────────────
        if cvss_score or cvss_metrics:
            lines += [
                "## CVSS",
                "",
            ]
            if cvss_score:
                lines.append(f"**Score:** `{cvss_score}`")
            if cvss_metrics:
                lines.append(f"**Vector:** `{cvss_metrics}`")
            if cwe_ids:
                lines.append(f"**CWE:** {', '.join(f'`{c}`' for c in cwe_ids)}")
            lines.append("")

        # ── AI analysis summary (clearly labelled as AI output) ───────────
        if ai_analysis and ai_analysis.output:
            ai_out: dict = ai_analysis.output
            lines += [
                "## AI Triage (Unverified — Requires Human Review)",
                "",
                "### Why This Might Matter",
                "",
                ai_out.get("understanding", "_No AI analysis available._"),
                "",
                "### Technical Context",
                "",
                ai_out.get("why_vulnerable", "_N/A_"),
                "",
                "### False Positive Considerations",
                "",
                ai_out.get("false_positive_possibilities", "_Unknown._"),
                "",
            ]
        else:
            lines += [
                "## AI Triage",
                "",
                "_No AI analysis has been performed for this finding._",
                "",
            ]

        # ── Evidence ─────────────────────────────────────────────────────
        lines += [
            "## Collected Evidence",
            "",
            "> Evidence below was collected by the scanner at detection time.",
            "> Review each item and supplement with manual testing before submission.",
            "",
        ]

        if evidence:
            for ev in evidence:
                kind_label = str(ev.kind.value if hasattr(ev.kind, "value") else ev.kind)
                lines += [
                    f"### Evidence: {kind_label.replace('_', ' ').title()}",
                    "",
                    f"- **Collected by:** `{ev.collected_by}`",
                    f"- **Collected at:** `{ev.collected_at.isoformat()}`",
                    f"- **SHA-256:** `{ev.sha256}`",
                    f"- **Reference:** `{ev.content_ref[:200]}`",
                ]

                raw_req = getattr(ev, "raw_request", None)
                raw_resp = getattr(ev, "raw_response", None)
                ev_curl = getattr(ev, "curl_command", None)
                human_verified = getattr(ev, "is_verified_by_human", False)

                if human_verified:
                    lines.append("- ✅ **Verified by human reviewer**")
                else:
                    lines.append("- ⚠️ **Automated — not yet verified by human**")

                if raw_req:
                    lines += [
                        "",
                        "**HTTP Request (as captured):**",
                        "```http",
                        raw_req[:1500],
                        "```",
                    ]
                if raw_resp:
                    lines += [
                        "",
                        "**HTTP Response (as captured):**",
                        "```http",
                        raw_resp[:1500],
                        "```",
                    ]
                if ev_curl:
                    lines += [
                        "",
                        "**Reproduction Command (from evidence):**",
                        "```bash",
                        ev_curl,
                        "```",
                    ]
                lines.append("")
        else:
            lines += [
                "⚠️ **No evidence records found for this finding.**",
                "",
                "Before submission, you must manually capture and attach:",
                "- The actual HTTP request and response demonstrating the issue.",
                "- A reproducible curl command.",
                "- Proof of impact.",
                "",
            ]

        # ── Extracted results from scanner ────────────────────────────────
        if extracted_results:
            lines += [
                "## Scanner Extracted Results",
                "",
                "_These are raw values matched by the scanner template. Verify manually._",
                "",
            ]
            for res in extracted_results[:10]:
                lines.append(f"- `{self._esc(str(res))}`")
            lines.append("")

        # ── Reproduction (curl from scope_result or placeholder) ──────────
        lines += ["## Reproduction Steps", ""]
        if curl_command:
            lines += [
                "The scanner recorded the following command. **Verify manually before submitting.**",
                "",
                "```bash",
                curl_command,
                "```",
                "",
            ]
        else:
            lines += [
                "⚠️ No reproduction command was automatically captured.",
                "",
                "Before submitting, provide:",
                "1. The exact URL/endpoint affected.",
                "2. The HTTP method, headers, and request body.",
                "3. Any prerequisites (authentication, specific state, etc.).",
                "4. The exact response or behavior demonstrating the issue.",
                "5. A curl or HTTP proxy export showing the full exchange.",
                "",
            ]

        # ── AI suggested safe next steps ──────────────────────────────────
        if ai_analysis and ai_analysis.output.get("safe_verification_steps"):
            lines += [
                "## Suggested Safe Verification Steps (AI — Unverified)",
                "",
                "> Treat these as research suggestions, not authoritative confirmation.",
                "",
            ]
            for step in ai_analysis.output["safe_verification_steps"]:
                lines.append(f"- {step}")
            lines.append("")

        # ── Remediation ───────────────────────────────────────────────────
        if ai_analysis and ai_analysis.output.get("remediation"):
            lines += [
                "## Remediation Guidance (AI-Suggested — Verify with Development Team)",
                "",
                ai_analysis.output["remediation"],
                "",
            ]
        else:
            lines += [
                "## Remediation",
                "",
                "_Consult your development team and applicable security standards (OWASP, CWE)._",
                "_This section must be completed with specific guidance before submission._",
                "",
            ]

        # ── Scope confirmation ────────────────────────────────────────────
        lines += [
            "## Scope Confirmation",
            "",
            f"Scanner recorded matched asset: `{matched_at or 'Not recorded'}`",
            "",
            f"Program: **{program.name if program else 'Unknown'}**",
            "",
            "> ⚠️ You must independently confirm that the affected asset is explicitly listed",
            "> in the program scope before submission. Do not rely on scanner output alone.",
            "",
            "---",
            "",
            "## Review Checklist",
            "",
            "Before submitting this report, verify each item:",
            "",
            "- [ ] I have manually reproduced this issue.",
            "- [ ] The affected asset is explicitly in-scope.",
            "- [ ] I have attached real HTTP request/response evidence.",
            "- [ ] The severity assessment reflects actual impact.",
            "- [ ] The reproduction steps are accurate and complete.",
            "- [ ] No personal data or secrets appear in this report.",
            "- [ ] The program permits this testing method.",
            "- [ ] I have read and followed the program disclosure policy.",
            "",
            "---",
            "",
            "_Generated by BugHunter AI · Draft · Not submitted_",
        ]

        return "\n".join(lines)

    # ------------------------------------------------------------------ #
    # PDF wrapper                                                           #
    # ------------------------------------------------------------------ #

    def generate_pdf(self, markdown: str, output_path: str) -> str:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import cm
        from reportlab.lib import colors
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable

        doc = SimpleDocTemplate(
            output_path,
            pagesize=A4,
            rightMargin=2 * cm,
            leftMargin=2 * cm,
            topMargin=2 * cm,
            bottomMargin=2 * cm,
        )
        styles = getSampleStyleSheet()
        warn_style = ParagraphStyle("warn", parent=styles["Normal"], textColor=colors.red)
        story = []

        for line in markdown.split("\n"):
            stripped = line.strip()
            if stripped.startswith("# "):
                story.append(Paragraph(stripped[2:], styles["Title"]))
            elif stripped.startswith("## "):
                story.append(Spacer(1, 0.3 * cm))
                story.append(Paragraph(stripped[3:], styles["Heading2"]))
            elif stripped.startswith("### "):
                story.append(Paragraph(stripped[4:], styles["Heading3"]))
            elif stripped.startswith("---"):
                story.append(HRFlowable(width="100%", thickness=0.5, color=colors.grey))
            elif "⚠️" in stripped or "DRAFT" in stripped:
                story.append(Paragraph(stripped.replace("`", "").replace("*", ""), warn_style))
            elif stripped:
                story.append(Paragraph(stripped.replace("`", ""), styles["Normal"]))
            else:
                story.append(Spacer(1, 0.2 * cm))

        doc.build(story)
        return output_path

    # ------------------------------------------------------------------ #
    # Helpers                                                               #
    # ------------------------------------------------------------------ #

    @staticmethod
    def _esc(value: str) -> str:
        """Escape Markdown pipe characters in table values."""
        return str(value).replace("|", "\\|")
