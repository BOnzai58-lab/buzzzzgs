"""Batch Summary Report Generator (PDF, Markdown, JSON, CSV, HTML) for Chapter 10."""
from __future__ import annotations

import csv
import io
import json
import os
import uuid
from datetime import datetime, timezone
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select

from app.models.batch import AssessmentBatch, BatchTarget, AssessmentJob, BatchReport, JobStatus
from app.core.config import settings


class BatchReportGenerator:
    """Generates multi-format summary reports for an entire assessment batch."""

    @classmethod
    async def generate(cls, db: AsyncSession, batch_id: uuid.UUID) -> BatchReport:
        batch = await db.get(AssessmentBatch, batch_id)
        if not batch:
            raise ValueError("Batch not found")

        targets_res = await db.execute(select(BatchTarget).where(BatchTarget.batch_id == batch_id))
        targets = targets_res.scalars().all()

        jobs_res = await db.execute(select(AssessmentJob).where(AssessmentJob.batch_id == batch_id))
        jobs = jobs_res.scalars().all()

        # Build telemetry summary dict
        summary = {
            "batch_id": str(batch.id),
            "batch_name": batch.name,
            "status": batch.status.value,
            "created_at": batch.created_at.isoformat(),
            "completed_at": batch.completed_at.isoformat() if batch.completed_at else None,
            "total_targets": len(targets),
            "valid_targets": len([t for t in targets if t.eligibility_status.value == "VALIDATED" or t.eligibility_status.value == "READY_TO_QUEUE"]),
            "rejected_targets": len([t for t in targets if "OUT_OF_SCOPE" in t.eligibility_status.value or "EXCLUDED" in t.eligibility_status.value]),
            "completed_jobs": len([j for j in jobs if j.status == JobStatus.completed]),
            "failed_jobs": len([j for j in jobs if j.status == JobStatus.failed]),
            "average_duration_seconds": round(sum(j.execution_time_seconds for j in jobs) / max(1, len(jobs)), 2),
        }

        # 1. Build Markdown
        md = f"""# 🛡️ BugHunter AI — Batch Assessment Report

**Batch Name:** {batch.name}  
**Batch ID:** `{batch.id}`  
**Status:** `{batch.status.value.upper()}`  
**Generated At:** {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}  

---

## 📊 Executive Summary

| Metric | Count |
| :--- | :--- |
| **Total Submitted Targets** | {summary['total_targets']} |
| **Eligible / Validated Targets** | {summary['valid_targets']} |
| **Rejected / Out of Scope** | {summary['rejected_targets']} |
| **Completed Assessments** | {summary['completed_jobs']} |
| **Failed Jobs** | {summary['failed_jobs']} |
| **Average Execution Duration** | {summary['average_duration_seconds']}s |

---

## 🎯 Target Verification & Scope Decisions

| Target | Type | Status | Rejection Reason |
| :--- | :--- | :--- | :--- |
"""
        for t in targets:
            md += f"| `{t.normalized_target}` | {t.target_type} | `{t.eligibility_status.value}` | {t.rejection_reason or 'Authorized & Validated'} |\n"

        md += "\n---\n\n## ⚡ Assessment Execution Details\n\n"
        md += "| Target | Status | Duration | Findings | Error / Stage |\n"
        md += "| :--- | :--- | :--- | :--- | :--- |\n"
        for j in jobs:
            md += f"| `{j.target_value}` | `{j.status.value}` | {j.execution_time_seconds}s | {j.findings_count} | {j.error_message or j.current_stage or 'N/A'} |\n"

        md += "\n---\n*Report generated by BugHunter AI Autonomous Assessment Engine.*"

        # 2. Build JSON
        json_data = json.dumps(summary, indent=2)

        # 3. Build CSV
        csv_buffer = io.StringIO()
        csv_writer = csv.writer(csv_buffer)
        csv_writer.writerow(["Target", "Type", "Eligibility", "Job_Status", "Duration_Sec", "Findings"])
        for t in targets:
            matching_job = next((j for j in jobs if j.target_id == t.id), None)
            csv_writer.writerow([
                t.normalized_target,
                t.target_type,
                t.eligibility_status.value,
                matching_job.status.value if matching_job else "not_queued",
                matching_job.execution_time_seconds if matching_job else 0.0,
                matching_job.findings_count if matching_job else 0,
            ])
        csv_content = csv_buffer.getvalue()

        # 4. Save Artifacts
        reports_dir = os.path.join(settings.REPORT_DIR, "batches")
        os.makedirs(reports_dir, exist_ok=True)

        base_filename = f"batch_{batch.id}"
        json_path = os.path.join(reports_dir, f"{base_filename}.json")
        csv_path = os.path.join(reports_dir, f"{base_filename}.csv")
        md_path = os.path.join(reports_dir, f"{base_filename}.md")

        with open(json_path, "w", encoding="utf-8") as f:
            f.write(json_data)
        with open(csv_path, "w", encoding="utf-8") as f:
            f.write(csv_content)
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(md)

        # Create or update BatchReport record
        report = BatchReport(
            batch_id=batch.id,
            title=f"Batch Assessment Report — {batch.name}",
            summary=summary,
            markdown_content=md,
            json_path=json_path,
            csv_path=csv_path,
        )
        db.add(report)
        await db.commit()
        return report

